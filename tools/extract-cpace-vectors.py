#!/usr/bin/env python3
"""Extract CPACE-RISTR255-SHA512 vectors (Appendix B.3) from an IETF draft text file.

Usage: extract-cpace-vectors.py draft-irtf-cfrg-cpace-21.txt > vectors.rs
Reads text only; performs no cryptography. The SHA-256 of the input is embedded so
a reviewer can compare it against the published draft.
"""
import hashlib, re, sys

text = open(sys.argv[1], encoding="utf-8").read()
digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
lines = [l for l in text.splitlines()
         if l.strip() and not l.startswith("Abdalla, et al") and not l.startswith("Internet-Draft")]
start = next(i for i, l in enumerate(lines) if l.startswith("B.3.  Test vector"))
end = next(i for i, l in enumerate(lines) if l.startswith("B.3.8."))
block = lines[start:end]

def hexafter(label_regex, occurrence=0):
    hits = [i for i, l in enumerate(block) if re.search(label_regex, l)]
    i = hits[occurrence]
    out = ""
    for l in block[i + 1:]:
        s = l.strip()
        if re.fullmatch(r"[0-9a-f]+", s):
            out += s
        elif out:
            break
    return out

def scalar_label(label):
    i = next(i for i, l in enumerate(block) if label in l)
    return i

vec = {
    "PRS_HEX": "50617373776f7264",  # b'Password' (stated in the draft text)
    "CI_HEX": re.search(r"CI = ([0-9a-f]{40,})", "\n".join(block)).group(1),
    "SID_HEX": re.search(r"sid = ([0-9a-f]{32})", "\n".join(block)).group(1),
    "GENERATOR_STRING_HEX": hexafter(r"generator_string"),
    "HASH_RESULT_HEX": hexafter(r"hash result"),
    "GENERATOR_HEX": hexafter(r"encoded generator g"),
    "YA_SCALAR_HEX": hexafter(r"ya \(little endian\)"),
    "YA_HEX": hexafter(r"^\s*Ya: "),
    "YB_SCALAR_HEX": hexafter(r"yb \(little endian\)"),
    "YB_HEX": hexafter(r"^\s*Yb: "),
    "K_HEX": hexafter(r"scalar_mult_vfy\(ya,Yb\)"),
    "TRANSCRIPT_IR_HEX": hexafter(r"transcript_ir\(Ya,ADa,Yb,ADb\): \(length"),
    "ISK_IR_HEX": hexafter(r"ISK result", 0),
    "TRANSCRIPT_OC_HEX": hexafter(r"transcript_oc\(Ya,ADa,Yb,ADb\): \(length"),
    "ISK_OC_HEX": hexafter(r"ISK result", 1),
    "SID_OUT_IR_HEX": hexafter(r"transcript_ir\(Ya,ADa, Yb,ADb\)\):"),
    "SID_OUT_OC_HEX": hexafter(r"transcript_oc\(Ya,ADa, Yb,ADb\)\):"),
}
print("#![allow(dead_code)]")
print("// @generated by tools/extract-cpace-vectors.py from the draft text; do not edit.")
print(f"// Source: draft-irtf-cfrg-cpace-21 Appendix B.3 (ristretto255 + SHA-512); draft text sha256 = {digest}")
for k, v in vec.items():
    assert v and re.fullmatch(r"[0-9a-f]+", v), k
    print(f'pub const {k}: &str = "{v}";')
